package dev.affogato.golden;

public class BitwiseOperators {
    public int andOp(int a, int b) {
        return a & b;
    }

    public int orOp(int a, int b) {
        return a | b;
    }

    public int xorOp(int a, int b) {
        return a ^ b;
    }

    public int complementOp(int a) {
        return ~a;
    }

}
